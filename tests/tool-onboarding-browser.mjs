import { mkdtemp, mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { chromium, expect } from '@playwright/test'

const profile = await mkdtemp(join(tmpdir(), 'toolglows-onboarding-'))
const extension = resolve('dist/chrome')
const output = resolve('.playwright-mcp/onboarding')
await mkdir(output, { recursive: true })
const options = { executablePath: chromium.executablePath(), headless: true, reducedMotion: 'reduce',
  args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`] }
let context = await chromium.launchPersistentContext(profile, options)
const cookieKey = 'toolglowsCookieConsent'
const skipKey = 'toolglowsOnboarding.v1.skipAll'
async function workerFor(ctx) { return ctx.serviceWorkers()[0] ?? await ctx.waitForEvent('serviceworker') }
async function fixture(ctx) {
  const page = await ctx.newPage()
  await page.route('https://example.com/**', route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: `<!doctype html><html><body>
    <h1>Une page à lire</h1><p>Cette page permet de vérifier les outils.</p>
    <div id="onetrust-banner-sdk"><p>Cookies</p><button id="onetrust-accept-btn-handler" onclick="document.body.dataset.accepted='yes';this.parentElement.remove()">Accept all cookies</button></div>
  </body></html>` }))
  await page.goto('https://example.com/onboarding-proof')
  await page.locator('#toolglows-root').waitFor()
  const main = page.getByRole('button', { name: 'ToolGlows', exact: true })
  await main.waitFor({ state: 'visible' })
  if (!await page.locator('[data-tool-id="cookieConsent"]').isVisible()) await main.click()
  await page.locator('[data-toolglows-settings]').click()
  await page.locator('#pinBar').check()
  await page.keyboard.press('Escape')
  return page
}
try {
  let worker = await workerFor(context)
  const base = `chrome-extension://${new URL(worker.url()).host}`
  const welcome = await context.newPage()
  await welcome.goto(`${base}/src/ui/setup/index.html#/setup/install`)
  await expect(welcome.getByRole('heading', { name: 'Vos outils web, au même endroit.' })).toBeVisible()
  await expect(welcome.locator('[data-tool-catalog-id]')).toHaveCount(18)
  await welcome.screenshot({ path: join(output, 'welcome.png'), fullPage: true })
  await welcome.getByRole('button', { name: 'Terminer' }).click()
  await expect(welcome.getByRole('heading', { name: 'À vous de jouer.' })).toBeVisible()
  expect(await worker.evaluate(key => chrome.storage.local.get(key), skipKey)).toEqual({})

  const page = await fixture(context)
  const cookie = page.locator('[data-tool-id="cookieConsent"]')
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  await cookie.click({ button: 'right' })
  let settings = page.getByRole('dialog', { name: 'Acceptation des cookies', exact: true })
  await expect(settings).toBeVisible()
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('Escape')
  await cookie.click()
  const intro = page.getByRole('dialog', { name: 'Découvrir : Acceptation des cookies' })
  await expect(intro).toBeVisible()
  await expect(page.locator('#onetrust-banner-sdk')).toBeVisible()
  await page.waitForTimeout(350)
  await page.screenshot({ path: join(output, 'cookie-introduction.png'), fullPage: true })
  await intro.getByRole('button', { name: 'Plus tard', exact: true }).click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  await cookie.focus()
  await page.keyboard.press('Enter')
  await intro.getByRole('button', { name: 'Activer', exact: true }).click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#onetrust-banner-sdk')).toHaveCount(0)
  await cookie.click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  await expect(intro).toHaveCount(0)
  await cookie.click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'true')
  await cookie.focus()
  await page.keyboard.press('Shift+F10')
  await expect(settings).toBeVisible()
  await page.locator('#cookie-consent-excluded').check()
  await expect(cookie).toHaveAttribute('title', /ce site est exclu/)
  await page.keyboard.press('Escape')
  await cookie.click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  await cookie.click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.locator('#onetrust-banner-sdk')).toBeVisible()
  await page.getByRole('button', { name: 'ToolGlows', exact: true }).waitFor({ state: 'visible' })
  if (!await cookie.isVisible()) await page.getByRole('button', { name: 'ToolGlows', exact: true }).click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'true')
  await cookie.click()
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  // Global skip never invokes the pending command or changes cookie preferences.
  await page.locator('[data-tool-id="linksExplorer"]').click()
  await page.getByRole('button', { name: 'Ne plus afficher les explications', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(cookie).toHaveAttribute('aria-pressed', 'false')
  await page.locator('[data-tool-id="wordCount"]').click()
  await expect(page.locator('[data-tool-introduction]')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.locator('[data-toolglows-settings]').click()
  await page.getByRole('dialog').getByRole('button', { name: 'Acceptation des cookies', exact: true }).click()
  await expect(intro).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: join(output, 'introduction-narrow.png'), fullPage: true })
  expect((await intro.boundingBox()).width).toBeLessThanOrEqual(390)
  await page.keyboard.press('Escape')
  const state = await worker.evaluate(async keys => chrome.storage.local.get(keys), [cookieKey, skipKey])
  expect(state[skipKey]).toBe(true)
  expect(state[cookieKey]).toEqual({ enabled: false, excludedHosts: ['example.com'] })
  await welcome.goto(`${base}/src/ui/setup/index.html#/setup/update`)
  await expect(welcome.getByRole('heading', { name: 'Vos outils web, au même endroit.' })).toHaveCount(0)
  await expect(welcome).toHaveTitle(/Updated/)
  await context.close()
  context = await chromium.launchPersistentContext(profile, options)
  worker = await workerFor(context)
  const restarted = await fixture(context)
  const restartedCookie = restarted.locator('[data-tool-id="cookieConsent"]')
  await restartedCookie.click()
  await expect(restartedCookie).toHaveAttribute('aria-pressed', 'true')
  await expect(restarted.locator('[data-tool-introduction]')).toHaveCount(0)
  await expect(restarted.locator('#onetrust-banner-sdk')).toBeVisible()
  console.log('PASS: welcome, first use, defer, keyboard, real cookie toggle, right click, exclusions, skip-all, help, narrow viewport and browser restart')
} finally { await context.close() }
